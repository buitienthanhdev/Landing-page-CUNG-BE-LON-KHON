                const progress = Math.max(0, Math.min(1, scrolled / maxScroll));
                const maxTranslate = (2 / 3) * 100;

                track.style.transform = `translateX(-${progress * maxTranslate}%)`;
                if (tlFill) tlFill.style.width = `${progress * 100}%`;

                bars.forEach((bar, i) => {
                    if (!bar) return;
                    const start = i / total;
                    const end = (i + 1) / total;
                    if (progress >= end) bar.style.width = '100%';
                    else if (progress > start) bar.style.width = `${((progress - start) / (1 / total)) * 100}%`;
                    else bar.style.width = '0%';
                });

                const activeIndex = progress >= .66 ? 2 : progress >= .33 ? 1 : 0;
                if (activeIndex !== current) {
                    current = activeIndex;
                    updateUI(activeIndex, true);
                }
            }

            /* ── Track-wrap scroll → mobile tab sync ── */
            if (trackWrap) {
                trackWrap.addEventListener('scroll', () => {
                    if (isSyncing || isDesktop()) return;
                    const stageWidth = trackWrap.clientWidth;
                    if (stageWidth < 1) return;
                    const idx = Math.round(trackWrap.scrollLeft / stageWidth);
                    const clamped = Math.max(0, Math.min(total - 1, idx));
                    if (clamped !== current) {
                        current = clamped;
                        updateUI(clamped, true);
                    }
                }, { passive: true });
            }

            navItems.forEach(item => {
                item.addEventListener('click', () => setStage(item.dataset.stage, 'nav'));
            });

            tlNodes.forEach(node => {
                node.addEventListener('click', () => setStage(node.dataset.stage, 'nav'));
            });

            window.addEventListener('scroll', updateFromWindowScroll, { passive: true });
            window.addEventListener('resize', () => {
                // Reset transform so CSS handles it
                if (!isDesktop()) {
                    track.style.transform = '';
                    if (trackWrap) trackWrap.scrollTo({ left: current * trackWrap.clientWidth, behavior: 'instant' });
                } else {
                    if (trackWrap) trackWrap.scrollTo({ left: 0, behavior: 'instant' });
                    updateFromWindowScroll();
                }
            });
            desktopMq.addEventListener?.('change', () => {
                track.style.transform = '';
                current = 0;
                updateUI(0, true);
                if (trackWrap) trackWrap.scrollTo({ left: 0, behavior: 'instant' });
            });
            updateFromWindowScroll();
        });
    </script>

