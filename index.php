                    all[ci]?.classList.remove('center');
                    all[ti]?.classList.add('center');
                    setPosTrackIndex(ti, true);
                    S.cur = nextCur;
                    refreshUI();
                    setTimeout(() => {
                        if (ci === n && delta === 1) setPosTrackIndex(1, false);
